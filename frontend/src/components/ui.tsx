import type { ReactNode } from "react";
import { CircleAlert, CircleCheck, CircleDashed, Info, ShieldCheck, TriangleAlert } from "lucide-react";
import type { MonitoringState, Severity } from "../api/types";

/** Severity is always conveyed by icon + text; colour is supplementary (WCAG 1.4.1). */
const SEV: Record<string, { label: string; cls: string; Icon: typeof Info }> = {
  INFO: { label: "Info", cls: "bg-unknown-soft text-unknown", Icon: Info },
  MONITOR: { label: "Monitor", cls: "bg-monitor-soft text-monitor", Icon: CircleAlert },
  REVIEW: { label: "Review", cls: "bg-review-soft text-review", Icon: TriangleAlert },
  URGENT: { label: "Urgent", cls: "bg-urgent text-white", Icon: TriangleAlert },
};

export function SeverityBadge({ severity, className = "" }: { severity: Severity; className?: string }) {
  const s = SEV[severity] || SEV.INFO;
  return (
    <span className={`chip ${s.cls} ${className}`}>
      <s.Icon size={13} aria-hidden /> {s.label.toUpperCase()}
    </span>
  );
}

export const STATE_STYLE: Record<MonitoringState, { cls: string; Icon: typeof Info; short: string }> = {
  URGENT: { cls: "bg-urgent text-white border-urgent", Icon: TriangleAlert, short: "URGENT" },
  REVIEW: { cls: "bg-review-soft text-review border-review/40", Icon: TriangleAlert, short: "REVIEW" },
  MONITOR: { cls: "bg-monitor-soft text-monitor border-monitor/30", Icon: CircleAlert, short: "MONITOR" },
  WITHIN_CRITERIA: { cls: "bg-ok-soft text-ok border-ok/30", Icon: ShieldCheck, short: "WITHIN CRITERIA" },
  INCOMPLETE: { cls: "bg-unknown-soft text-unknown border-unknown/30", Icon: CircleDashed, short: "INCOMPLETE" },
};

export function StatePill({ state }: { state: MonitoringState }) {
  const s = STATE_STYLE[state] || STATE_STYLE.INCOMPLETE;
  return <span className={`chip border ${s.cls}`}><s.Icon size={13} aria-hidden /> {s.short}</span>;
}

export function AgentStatusBadge({ status }: { status: string }) {
  const map: Record<string, [string, string, typeof Info]> = {
    completed: ["Completed", "bg-ok-soft text-ok", CircleCheck],
    review: ["Needs review", "bg-review-soft text-review", TriangleAlert],
    insufficient_data: ["Insufficient data", "bg-unknown-soft text-unknown", CircleDashed],
    failed: ["Failed", "bg-urgent-soft text-urgent", CircleAlert],
    idle: ["Not activated", "bg-ivory-2 text-muted", CircleDashed],
    running: ["Running", "bg-sky/50 text-navy", CircleDashed],
  };
  const [label, cls, Icon] = map[status] || [status, "bg-ivory-2 text-muted", Info];
  return <span className={`chip ${cls}`}><Icon size={12} aria-hidden /> {label}</span>;
}

